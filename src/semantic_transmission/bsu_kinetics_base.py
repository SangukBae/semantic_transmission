"""Kinetics BSU adapter: actionable, bounded selection length repair.

Keep the initial prompt, semantic validator and accepted cached answers intact.
Only retry formatting after a state-description word-limit failure. Historical
WebVid workers retain their original retry policy and code hashes.
"""
from contextlib import contextmanager
import copy

from . import bsu_webvid_base as base, qwen35_feedback as feedback

MODULE = 'semantic_transmission.bsu_kinetics_base'
REPAIR_POLICY = 'selection_word_count_feedback_v1'


def length_feedback(failures):
    if not failures or 'at most 45 words total' not in failures[-1]['error']:
        return ''
    try:
        value=feedback.ae.parse_json(failures[-1]['raw_text'])
        states=[value[k] for k in ('reference_state','candidate_state')]
        if not all(isinstance(s,str) for s in states):return ''
    except (ValueError,TypeError,KeyError):
        return ''
    counts=[len(s.split()) for s in states]
    return ('\nSTATE LENGTH REPAIR: The previous reference_state has '
        f'{counts[0]} words and candidate_state has {counts[1]} words; '
        f'{sum(counts)} total exceeds the maximum 45. '
        'Use a short phrase of at most 12 words for EACH state (24 total). '
        'Omit articles, repeated scene/background details and decorative adjectives. '
        'Keep the visible subject and the relevant pose, position or visibility difference. '
        'This error concerns description length only; do not flip the decision, change the '
        'kind or invent evidence merely to shorten the response. Recheck the same supplied images. '
        'Count both state descriptions before returning the complete compact JSON.')


def rebind_selection_record(record, old_plan, new_plan, origin):
    """Reuse a validated answer only when adding this formatting-only adapter.

    The old sealed file remains in the repair archive. The new record explicitly
    cites it rather than claiming that the answer was generated by new code.
    """
    from .artifacts import sha256
    from .qwen35_semantic_selection import validate_decision
    for plan in (old_plan,new_plan):
        if feedback.ae.digest({k:v for k,v in plan.items() if k!='signature'})!=plan['signature']:
            raise ValueError('selection plan signature changed')
    excluded={'signature','template_sha256','code'}
    if {k:v for k,v in old_plan.items() if k not in excluded}!={k:v for k,v in new_plan.items() if k not in excluded}:
        raise ValueError('selection inputs or policy changed beyond formatting repair')
    expected=dict(old_plan['code'],**{'src/semantic_transmission/bsu_kinetics_base.py':sha256(__file__)})
    if new_plan['code']!=expected:raise ValueError('selection implementation change exceeds repair adapter')
    if feedback.ae.unseal(origin)!=record:raise ValueError('original sealed response changed')
    identity=record['identity'];ids=identity['ids']
    if (identity['plan_signature']!=old_plan['signature'] or len(ids)<2
            or identity['role'] not in ('semantic_select','semantic_select_schema','semantic_select_review','semantic_select_review_schema')
            or identity['frame_hashes']!=[old_plan['source']['source_frame_hashes'][str(i)] for i in ids]):
        raise ValueError('cached answer does not belong to the old source selection')
    feedback.Session(None,{}).validate_record(record,lambda value:validate_decision(value,ids[0],ids[-1]))
    result=copy.deepcopy(record);result['identity']['plan_signature']=new_plan['signature']
    result['reuse_provenance']=dict(policy=REPAIR_POLICY,source_record=str(origin),source_sha256=sha256(origin),
        produced_with_plan=old_plan['signature'],reused_for_plan=new_plan['signature'],raw_response_unchanged=True)
    return result


@contextmanager
def current_pipeline():
    """Set both parent dispatch and nested worker dispatch to this adapter."""
    module,repair=base.MODULE,feedback.response_repair_prompt
    def repaired(prompt,failures):
        return repair(prompt,failures)+length_feedback(failures)
    base.MODULE=MODULE;feedback.response_repair_prompt=repaired
    try:yield
    finally:base.MODULE=module;feedback.response_repair_prompt=repair


def main():
    with current_pipeline():base.main()


if __name__=='__main__':main()
